@api.websocket("/api/ws")
async def websocket_events(ws: WebSocket):
    """
    Real-time channel for the operator UI.
    Server -> client: {"seq", "type", "data", "timestamp"} for every board change,
                      plus {"type": "init", "seq", "data": overview} on connect/resync.
    Client -> server: {"type": "ping"} -> {"type": "pong"}
                      {"type": "resume", "last_seq": n} -> missed events, or a fresh init.
    """
    await ws.accept()
    queue = hub.subscribe()

    async def send_init():
        await ws.send_text(json.dumps({"type": "init", "seq": hub.last_seq, "data": db.get_overview()},
                                      default=str))

    async def pump_events():
        while True:
            await ws.send_text(await queue.get())

    async def read_client():
        while True:
            msg = json.loads(await ws.receive_text())
            if msg.get("type") == "ping":
                await ws.send_text(json.dumps({"type": "pong", "seq": hub.last_seq}))
            elif msg.get("type") == "resume":
                missed = hub.events_after(int(msg.get("last_seq", 0)))
                if missed is None:
                    await send_init()
                else:
                    for event in missed:
                        await ws.send_text(json.dumps(event, default=str))

    await send_init()
    pump = asyncio.create_task(pump_events())
    reader = asyncio.create_task(read_client())
    try:
        await asyncio.wait({pump, reader}, return_when=asyncio.FIRST_COMPLETED)
    except WebSocketDisconnect:
        pass
    finally:
        pump.cancel()
        reader.cancel()
        hub.unsubscribe(queue)

@api.get("/api/events")
async def sse_events(request: Request):
    """Server-Sent Events fallback (same hub as the WebSocket) for clients without WS."""
    queue = hub.subscribe()

    async def event_generator():
        yield f"data: {json.dumps({'type': 'init', 'seq': hub.last_seq, 'data': db.get_overview()}, default=str)}\n\n"
        try:
            while not await request.is_disconnected():
                try:
                    yield f"data: {await asyncio.wait_for(queue.get(), timeout=20.0)}\n\n"
                except asyncio.TimeoutError:
                    yield ": heartbeat\n\n"
        except asyncio.CancelledError:
            pass
        finally:
            hub.unsubscribe(queue)

    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "Connection": "keep-alive", "X-Accel-Buffering": "no"}
    )
